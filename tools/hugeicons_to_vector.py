#!/usr/bin/env python3
"""Convert Hugeicons (free, MIT) stroke-rounded icons into Android vector drawables.

Reads the icon data files from the @hugeicons/core-free-icons npm package
(dist/esm/<Name>Icon.js) without executing them, and writes
app/src/main/res/drawable/<drawable>.xml for each entry in ICONS.

Usage:
  npm pack @hugeicons/core-free-icons && tar -xzf hugeicons-core-free-icons-*.tgz
  python3 tools/hugeicons_to_vector.py package/dist/esm
"""

import os
import re
import sys

# drawable name -> (Hugeicons icon name, filled?)
ICONS = {
    "ic_search": ("Search01", False),
    "ic_close": ("Cancel01", False),
    "ic_back": ("ArrowLeft02", False),
    "ic_bookmark": ("Bookmark01", False),
    "ic_bookmark_filled": ("Bookmark01", True),
    "ic_share": ("Share08", False),
    "ic_speaker": ("VolumeHigh", False),
    "ic_settings": ("SlidersHorizontal", False),
    "ic_open_full": ("ArrowExpand01", False),
    "ic_chevron_right": ("ArrowRight01", False),
    "ic_copy": ("Copy01", False),
    "ic_sparkle": ("Sparkles", False),
}

ELEMENT = re.compile(r'\["path",\s*\{(.*?)\}\]', re.S)
ATTR = re.compile(r'(\w+):\s*"([^"]*)"')


def convert(js_text, filled):
    paths = []
    for body in ELEMENT.findall(js_text):
        attrs = dict(ATTR.findall(body))
        d = attrs["d"]
        stroke = attrs.get("stroke") == "currentColor"
        fill = filled or attrs.get("fill") == "currentColor"
        lines = [f'    <path\n        android:pathData="{d}"']
        if fill:
            lines.append('        android:fillColor="@android:color/white"')
        if stroke:
            lines.append('        android:strokeColor="@android:color/white"')
            lines.append(f'        android:strokeWidth="{attrs.get("strokeWidth", "1.5")}"')
            lines.append(f'        android:strokeLineCap="{attrs.get("strokeLinecap", "butt")}"')
            lines.append(f'        android:strokeLineJoin="{attrs.get("strokeLinejoin", "miter")}"')
        paths.append("\n".join(lines) + " />\n")
    if not paths:
        raise ValueError("no <path> elements found")
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Hugeicons (MIT, hugeicons.com). Generated by tools/hugeicons_to_vector.py. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp" android:height="24dp"\n'
            '    android:viewportWidth="24" android:viewportHeight="24"\n'
            '    android:tint="?android:attr/textColorSecondary">\n'
            + "".join(paths) + "</vector>\n")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = sys.argv[1]
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "app/src/main/res/drawable")
    for drawable, (name, filled) in ICONS.items():
        with open(os.path.join(src, f"{name}Icon.js"), encoding="utf-8") as f:
            xml = convert(f.read(), filled)
        with open(os.path.join(out, f"{drawable}.xml"), "w", encoding="utf-8") as f:
            f.write(xml)
        print(f"{drawable:20s} <- {name}{' (filled)' if filled else ''}")


if __name__ == "__main__":
    main()
