#!/usr/bin/env python3
"""Generate the PopUp Dictionary launcher icon.

Draws one design (indigo background; a white popup card with a serif "Aa"
whose tail points at an amber "highlighted word") and writes:

  app/src/main/res/drawable/ic_launcher_background.xml   adaptive icon background
  app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive icon foreground
  app/src/main/res/drawable/ic_launcher_monochrome.xml   themed-icon silhouette (Android 13+)
  docs/store/icon.svg                                     master, for the 512 px Play Store PNG

The "Aa" outlines come from DejaVu Serif Bold (Bitstream Vera license). Needs
fontTools:  pip install fonttools
Usage:      python3 tools/make_icon.py [--font /path/to/DejaVuSerif-Bold.ttf]
"""

import argparse
import os

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

# Adaptive icons are 108 x 108 units; launchers show roughly the central 72
# and keep the central 66-unit circle unmasked, so everything sits inside it.
INDIGO_DARK = "#2C40A8"
INDIGO_LIGHT = "#4766E0"
CARD = "#FFFFFF"
GLYPH = "#2F45B5"
HIGHLIGHT = "#FFC64D"

CARD_X, CARD_Y, CARD_W, CARD_H, CARD_R = 32.0, 30.0, 44.0, 32.0, 8.0
TAIL = [(49.0, 62.0), (54.0, 68.5), (59.0, 62.0)]
BAR_X, BAR_Y, BAR_W, BAR_H, BAR_R = 40.0, 73.0, 28.0, 5.5, 2.75


def rounded_rect(x, y, w, h, r):
    return (f"M{x + r},{y} H{x + w - r} A{r},{r} 0 0 1 {x + w},{y + r} V{y + h - r} "
            f"A{r},{r} 0 0 1 {x + w - r},{y + h} H{x + r} A{r},{r} 0 0 1 {x},{y + h - r} "
            f"V{y + r} A{r},{r} 0 0 1 {x + r},{y} Z")


def card_with_tail():
    """The card outline including the downward tail, as one closed path."""
    x, y, w, h, r = CARD_X, CARD_Y, CARD_W, CARD_H, CARD_R
    (lx, ly), (tx, ty), (rx, ry) = TAIL
    return (f"M{x + r},{y} H{x + w - r} A{r},{r} 0 0 1 {x + w},{y + r} V{y + h - r} "
            f"A{r},{r} 0 0 1 {x + w - r},{y + h} H{rx} L{tx},{ty} L{lx},{ly} "
            f"H{x + r} A{r},{r} 0 0 1 {x},{y + h - r} V{y + r} A{r},{r} 0 0 1 {x + r},{y} Z")


def glyph_path(font_path, text="Aa", height=17.0):
    """Outlines of `text`, scaled to cap height `height` and centred in the card."""
    font = TTFont(font_path)
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    cap = getattr(font["OS/2"], "sCapHeight", 0)
    if not cap:  # older fonts: measure the "A" instead
        from fontTools.pens.boundsPen import BoundsPen
        bp = BoundsPen(gs)
        gs[cmap[ord("A")]].draw(bp)
        cap = bp.bounds[3]
    scale = height / cap
    names = [cmap[ord(ch)] for ch in text]
    advance = sum(gs[n].width for n in names) - 40  # slight tightening between A and a
    total_w = advance * scale
    origin_x = CARD_X + CARD_W / 2 - total_w / 2
    baseline = CARD_Y + CARD_H / 2 + height / 2
    pen = SVGPathPen(gs)
    x = 0.0
    for n in names:
        # font units: y up; icon units: y down
        tpen = TransformPen(pen, (scale, 0, 0, -scale, origin_x + x * scale, baseline))
        gs[n].draw(tpen)
        x += gs[n].width - 20
    return pen.getCommands()


def vector(paths, tint=None):
    head = ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tools/make_icon.py; edit that script, not this file. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n')
    return head + "".join(paths) + "</vector>\n"


def path(d, fill, even_odd=False):
    rule = '\n        android:fillType="evenOdd"' if even_odd else ""
    return (f'    <path android:fillColor="{fill}"{rule}\n'
            f'        android:pathData="{d}" />\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default="/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf")
    args = ap.parse_args()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    drawable = os.path.join(root, "app/src/main/res/drawable")
    store = os.path.join(root, "docs/store")
    os.makedirs(store, exist_ok=True)

    card = card_with_tail()
    bar = rounded_rect(BAR_X, BAR_Y, BAR_W, BAR_H, BAR_R)
    aa = glyph_path(args.font)

    background = vector([
        '    <path android:pathData="M0,0 H108 V108 H0 Z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient android:type="linear"\n'
        '                android:startX="0" android:startY="0" android:endX="108" android:endY="108">\n'
        f'                <item android:offset="0" android:color="{INDIGO_LIGHT}" />\n'
        f'                <item android:offset="1" android:color="{INDIGO_DARK}" />\n'
        '            </gradient>\n'
        '        </aapt:attr>\n'
        '    </path>\n'])
    foreground = vector([path(bar, HIGHLIGHT), path(card, CARD), path(aa, GLYPH)])
    # Themed icons tint one silhouette: the "Aa" is cut out of the card.
    monochrome = vector([path(bar, "#FFFFFFFF"), path(card + " " + aa, "#FFFFFFFF", even_odd=True)])

    for name, xml in [("ic_launcher_background.xml", background),
                      ("ic_launcher_foreground.xml", foreground),
                      ("ic_launcher_monochrome.xml", monochrome)]:
        with open(os.path.join(drawable, name), "w") as f:
            f.write(xml)

    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="512" height="512">
  <defs><linearGradient id="g" x1="0" y1="0" x2="108" y2="108" gradientUnits="userSpaceOnUse">
    <stop offset="0" stop-color="{INDIGO_LIGHT}"/><stop offset="1" stop-color="{INDIGO_DARK}"/>
  </linearGradient></defs>
  <rect x="0" y="0" width="108" height="108" fill="url(#g)"/>
  <path d="{bar}" fill="{HIGHLIGHT}"/>
  <path d="{card}" fill="{CARD}"/>
  <path d="{aa}" fill="{GLYPH}"/>
</svg>
'''
    with open(os.path.join(store, "icon.svg"), "w") as f:
        f.write(svg)
    print("wrote launcher icon drawables and docs/store/icon.svg")


if __name__ == "__main__":
    main()
